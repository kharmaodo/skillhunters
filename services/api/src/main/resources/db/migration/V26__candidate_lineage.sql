ALTER TABLE candidate_profile ADD COLUMN active_version BOOLEAN NOT NULL DEFAULT TRUE;
CREATE TABLE candidate_identity (
 id UUID PRIMARY KEY,
 pool_id UUID NOT NULL REFERENCES talent_pool(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 1,
 opposed BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE candidate_identity_member (
 candidate_id UUID PRIMARY KEY REFERENCES candidate_profile(id) ON DELETE CASCADE,
 identity_id UUID NOT NULL REFERENCES candidate_identity(id) ON DELETE CASCADE
);
CREATE INDEX candidate_identity_members ON candidate_identity_member(identity_id);
INSERT INTO candidate_identity(id,pool_id,opposed)
 SELECT c.id,d.pool_id,COALESCE(g.opposed,FALSE) FROM candidate_profile c JOIN document_import d ON d.id=c.import_id LEFT JOIN candidate_governance g ON g.candidate_id=c.id;
INSERT INTO candidate_identity_member(candidate_id,identity_id) SELECT id,id FROM candidate_profile;
CREATE TABLE candidate_contact_verification (
 candidate_id UUID PRIMARY KEY REFERENCES candidate_profile(id) ON DELETE CASCADE,
 email_key VARCHAR(64) NOT NULL,
 actor_id UUID NOT NULL,
 verified_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX candidate_verified_email ON candidate_contact_verification(email_key);
CREATE TABLE candidate_lineage_event (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 candidate_id UUID NOT NULL REFERENCES candidate_profile(id) ON DELETE CASCADE,
 decision_id UUID NOT NULL,
 actor_id UUID NOT NULL,
 action VARCHAR(30) NOT NULL,
 active_candidate_id UUID NOT NULL,
 source_revision_id UUID NOT NULL,
 publication_id UUID,
 candidate_version BIGINT NOT NULL,
 reason VARCHAR(500) NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX candidate_lineage_history ON candidate_lineage_event(candidate_id,sequence);
