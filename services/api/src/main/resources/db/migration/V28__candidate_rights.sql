CREATE TABLE candidate_rights_request (
 id UUID PRIMARY KEY,
 candidate_id UUID NOT NULL REFERENCES candidate_profile(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 1,
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('ACCESS','RECTIFICATION','APPEAL')),
 state VARCHAR(20) NOT NULL DEFAULT 'RECEIVED',
 received_at TIMESTAMP WITH TIME ZONE NOT NULL,
 due_at TIMESTAMP WITH TIME ZONE NOT NULL,
 policy_reference VARCHAR(200) NOT NULL,
 email_reference VARCHAR(200) NOT NULL,
 summary VARCHAR(1000) NOT NULL,
 verification_method VARCHAR(40),
 verification_reference VARCHAR(200),
 verification_binding VARCHAR(64),
 verified_at TIMESTAMP WITH TIME ZONE,
 prepared_version BIGINT,
 corrected_revision UUID,
 appeal_reviewed BOOLEAN NOT NULL DEFAULT FALSE,
 outcome VARCHAR(20),
 response_reference VARCHAR(200),
 closed_at TIMESTAMP WITH TIME ZONE,
 created_by UUID NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(candidate_id,email_reference)
);
CREATE INDEX candidate_rights_queue ON candidate_rights_request(state,due_at,id);
CREATE TABLE candidate_rights_event (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id UUID NOT NULL REFERENCES candidate_rights_request(id) ON DELETE CASCADE,
 actor_id UUID NOT NULL,
 action VARCHAR(40) NOT NULL,
 reference VARCHAR(200),
 reason VARCHAR(2000),
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX candidate_rights_history ON candidate_rights_event(request_id,sequence);
