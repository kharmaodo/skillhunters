-- Deliberately no FK cascade: minimal audit survives deletion of its source.
CREATE TABLE governance_audit (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id UUID NOT NULL UNIQUE,
 actor_id UUID,
 action VARCHAR(80) NOT NULL,
 object_id UUID,
 pool_id UUID,
 purpose VARCHAR(200),
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX governance_audit_pool_sequence ON governance_audit(pool_id,sequence);
